import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';

export async function exerciseReturnFreight({ db, request, send, read, master, oak, smith, short, ship, inn,
  commissionTrip, arrive, start, stop, logIn }) {
  const list = async () => (await request(inn, 200)).launches.returns;
  const purse = async who => (await request('/api/auth/me', 200, undefined, who.token)).profile;
  const fields = { fee: 8, ask: 32 };
  const post = (actor, data = fields, code = 200) => send(actor, 'postReturn', data, code);
  const ownOrder = async actor => (await read(actor)).returns.find(r => r.own);
  db.exec('UPDATE harborStores SET salt=32');
  const opening = await purse(oak);
  await post(undefined, fields, 401);
  await post(short, fields, 409);
  for (const args of [{fee:0,ask:32},{fee:19,ask:32},{fee:1,ask:1.2},{fee:8,ask:101}]) await post(oak,args,409);
  const slip = {...fields,nonce:randomUUID()};
  await Promise.all([post(oak,slip),post(oak,slip)]);
  await post(oak,{...slip,ask:40},409);
  assert.equal((await purse(oak)).gold, opening.gold-56);
  const cancelled = (await ownOrder(oak)).id;
  await send(master,'cancelReturn',{offer:cancelled},409);
  await send(oak,'cancelReturn',{offer:cancelled});
  assert.equal((await purse(oak)).gold, opening.gold);
  await post(oak);
  const expiring = (await ownOrder(oak)).id;
  db.prepare('UPDATE returnOrders SET expires=0 WHERE id=?').run(expiring);
  await read();
  assert.equal((await purse(oak)).gold, opening.gold);
  await post(oak);
  const offer = (await ownOrder(oak)).id;
  assert.equal((await list()).find(r=>r.id===offer).own,false);
  const charter = await commissionTrip();
  const trip = {...ship,charter};
  // The first skipper takes the salt out; only that skipper may commit the return hold.
  const captainGold = (await purse(smith)).gold;
  const unsupplemented = (await send(smith,'sail',trip)).ship.job;
  await send(master,'loadReturn',{...trip,offer},409);
  await post(smith);
  await send(smith,'loadReturn',{...trip,offer:(await ownOrder(smith)).id},409);
  const boarding = {...trip,offer,nonce:randomUUID()};
  const receipts = await Promise.all([send(smith,'loadReturn',boarding),send(smith,'loadReturn',boarding)]);
  assert.equal(receipts[0].ship.job.due,unsupplemented.due+12000);
  assert.equal((await ownOrder(oak)).state,'aboard');
  await send(smith,'emptyReturn',trip,409);
  await send(oak,'cancelReturn',{offer},409);
  await send(master,'buyReturn',{offer},409);
  await send(smith,'cancelReturn',{offer:(await ownOrder(smith)).id});
  assert.equal((await purse(smith)).gold,captainGold);
  await stop(); await start();
  for(const a of [master,oak,smith,short]) await logIn(a);
  assert.equal((await read(smith,'?ship='+ship.ship)).ship.job.due,receipts[0].ship.job.due);
  await arrive(charter);
  const landed = (await list()).find(r=>r.id===offer);
  assert.deepEqual([landed.state,landed.remaining,landed.vessel],['stall',2,'Skowronek']);
  assert.equal((await purse(smith)).gold,captainGold+18+8);
  assert.equal((await read(null,'?ship='+ship.ship)).ship.journal[0].backhaul.cargo.fee,8);
  await send(oak,'buyReturn',{offer},409);
  await send(short,'buyReturn',{offer},409);
  await send(smith,'collectReturn',{offer},409);
  const shopping = {offer,nonce:randomUUID()}, buyer = await purse(master);
  await Promise.all([send(master,'buyReturn',shopping),send(master,'buyReturn',shopping)]);
  assert.equal((await ownOrder(oak)).remaining,1);
  assert.equal((await purse(master)).inventory.zboze,buyer.inventory.zboze+1);
  assert.equal((await purse(master)).gold,buyer.gold-32);
  assert.equal((await purse(oak)).gold,opening.gold-56+32);
  await send(oak,'collectReturn',{offer});
  assert.equal((await purse(oak)).inventory.zboze,opening.inventory.zboze+1);
  await send(master,'buyReturn',{offer},409);
  assert.ok(!(await list()).some(r=>r.id===offer));
  await stop(); await start();
  for(const a of [master,oak,smith]) await logIn(a);
  assert.equal((await purse(smith)).gold,captainGold+26);
  await post(oak);
  const next = (await ownOrder(oak)).id;
  const plain = {...ship,charter:await commissionTrip()};
  const first = (await send(smith,'sail',plain)).ship.job;
  const empty = (await send(smith,'emptyReturn',plain)).ship.job;
  assert.equal(empty.due,first.due);
  assert.deepEqual(empty.backhaul,{cargo:null});
  await send(smith,'loadReturn',{...plain,offer:next},409);
  await arrive(plain.charter);
  const late = {...ship,charter:await commissionTrip()};
  await send(smith,'sail',late);
  // Advance only the isolated voyage to its homeward leg.
  db.prepare('UPDATE yardVoyages SET departed=?,due=? WHERE id=?').run(Date.now()-48000,Date.now()+12000,late.charter);
  await send(smith,'loadReturn',{...late,offer:next},409);
  assert.equal((await ownOrder(oak)).state,'open');
  await arrive(late.charter);
  const final = {...ship,charter:await commissionTrip()};
  await send(smith,'sail',final);
  await send(smith,'loadReturn',{...final,offer:next});
  await arrive(final.charter);
  await send(master,'buyReturn',{offer:next});
  const buyers = await Promise.allSettled([send(master,'buyReturn',{offer:next}),send(smith,'buyReturn',{offer:next})]);
  assert.equal(buyers.filter(x=>x.status==='fulfilled').length,1);
  assert.equal(buyers.find(x=>x.status==='rejected').reason.actual,409);
  assert.ok(!(await list()).some(r=>r.id===next));
}
